from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

app = FastAPI(title="Heart Health AI API")

# Allow CORS for the React frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],  # In production, specify the actual frontend URL
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

class PatientData(BaseModel):
    age: float
    sex: str
    cp: float
    trestbps: float
    chol: float
    fbs: str
    restecg: float
    thalach: float
    exang: str
    oldpeak: float
    slope: float
    ca: float
    thal: float

import os
from ml_engine import HeartDiseaseModelEngine

# Ensure dataset path is correct relative to backend/
DATA_PATH = os.path.join(os.path.dirname(__file__), "..", "heart_data.txt")
engine = HeartDiseaseModelEngine(DATA_PATH)

@app.get("/")
def read_root():
    return {"message": "Welcome to the Heart Health AI API"}

@app.post("/predict")
def predict_risk(data: PatientData):
    # Convert string categorical values to numerical as expected by the ML engine
    sex_num = 1 if data.sex.lower() == "male" else 0
    fbs_num = 1 if data.fbs.lower() == "yes" else 0
    exang_num = 1 if data.exang.lower() == "yes" else 0

    features = [
        data.age, sex_num, data.cp, data.trestbps, data.chol, 
        fbs_num, data.restecg, data.thalach, exang_num, 
        data.oldpeak, data.slope, data.ca, data.thal
    ]
    
    risk_percent = engine.predict(features)
    
    # TODO: Connect Gemini LLM here to generate dynamic diet plan
    # For now, returning basic rule-based output so frontend can be built
    return {
        "risk_score": risk_percent,
        "advice": {
            "nutrition": "Your AI personalized weekly diet plan will appear here.",
            "lifestyle": "Your AI personalized exercise routine will appear here.",
            "medical": "Medical insights generated by AI will appear here."
        }
    }
